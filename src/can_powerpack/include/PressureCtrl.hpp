#pragma once

// ============================================================================
// PressureCtrl — 채널 압력 PID 제어기
//
// 이 파일과 PressureCtrl.cpp 가 제어기의 전부다. 예전의 MPC/MPPI 계층(선형화 QP,
// 롤아웃 샘플링, 역모델 피드포워드, 온라인 보강)은 전부 지웠고, 남은 것은
// **채널마다 하나씩 도는 기본 PID (anti-windup 만 포함)** 하나다.
// 나머지(CAN 통신, 센서 환산, 목표압 수신, 위치·힘 외부 루프, 라인 PID,
// 과압 세이프티, PWM 발행)는 손대지 않았다.
//
// 출력 규칙:
//   u > 0 → micro = u,   atm = 0
//   u < 0 → atm = |u|,   micro = 0
//   macro 는 **항상 0** (부스트 경로를 쓰지 않는다)
//
// 채널(channel)은 축의 챔버 하나다. 6축 기본 구성에서
//   축 i 의 양압 챔버 : global_id = i,      pressure board 5+i
//   축 i 의 음압 챔버 : global_id = 6+i,    pressure board 11+i
// 이고 채널마다 밸브 3개(micro/macro/atm)를 가진다. 즉 축 하나에 이 제어기
// 인스턴스가 두 개 붙는다 (P⁺ 채널, P⁻ 채널).
//
// ── 한 틱의 경계 ────────────────────────────────────────────────────────────
//   Controller::on_timer()
//     → 채널마다 Input 을 채운다 (목표압·측정압·레일압·부피·dt)
//     → PressureCtrl::compute(in)  ★ 목표 압력 in, 밸브 명령 out
//     → PressureCtrl::to_pwm(out)  내부 %명령 → 보드 PWM 슬롯
//     → 과압 세이프티 · 라인 PID · board/pwm_cmd 발행
//
// ── 단위 ────────────────────────────────────────────────────────────────────
//   압력  : kPa **absolute** (대기압 ≈ 101.325). 게이지압이 아니다.
//   명령  : % (0 = 완전 폐쇄, 100 = 완전 개방). PWM 변환은 to_pwm() 이 한다.
//   시간  : s
//   부피  : m³
//
// ── 밸브 순서 주의 ──────────────────────────────────────────────────────────
//   이 클래스 안에서는 항상 {0=micro, 1=macro, 2=atm} 이다.
//   물리 보드의 PWM 슬롯은 {v1=micro, v2=atm, v3=macro} 로 순서가 다르다.
//   그 재배치는 to_pwm() 한 곳에만 있다.
//
//   micro : 레일(양압 채널은 P_line_pos, 음압 채널은 P_line_neg)에서 챔버로
//   macro : 부스트 경로 (양압은 탱크, 음압은 macro_neg 레일) — 지금은 쓰지 않는다
//   atm   : 대기 방출
//   세 밸브 모두 정상폐쇄(normally-closed) 비례 솔레노이드다.
// ============================================================================

#include <array>
#include <cstdint>

class PressureCtrl {
public:
  static constexpr int N_VALVE = 3;
  enum ValveIdx { V_MICRO = 0, V_MACRO = 1, V_ATM = 2 };

  // ── PID 게인 ──────────────────────────────────────────────────────────────
  // yaml 의 ChannelPID.{pos,neg}.* 에서 오고, 채널별로
  // channel_config.chN.pid.{kp,ki,kd} 로 덮어쓸 수 있다.
  //
  // 오차 e 는 **부호를 뒤집어** 쓴다 (compute 주석 참조): e_eff > 0 이면 micro 를
  // 열어야 하는 방향이다. 그래서 게인은 양압/음압 채널 모두 양수다.
  struct Gains {
    // 비례이득은 **구간별로 둘**이다. 하나의 선형 이득으로는 두 요구를 동시에
    // 만족할 수 없다는 것이 실측·시뮬로 확인됐다:
    //   · 목표 근처: 챔버 50 mL 에 레일 차압 80 kPa 면 플랜트가 10 kPa 스텝을
    //     40 ms 에 닫는다. 이득이 크면 22 Hz · p-p 9.4 kPa 로 링잉한다 (실기
    //     20260907_204249). 시뮬에서 kp=2.0 은 오버슛 14~31 kPa 였다.
    //   · 목표에서 멀 때: 유량이 부족한 구간이다. 이득이 작으면 밸브를 크래킹
    //     위로 못 밀어 아예 못 따라간다 (시뮬 kp=0.5, 20 kPa 스텝 도달 실패,
    //     정상상태 오차 15 kPa — 명령이 임계 위 5 %p 뿐이었다).
    // 그래서 밴드 안은 kp, 밖은 kp_far 를 쓰고 경계에서 연속이 되게 잇는다.
    float kp{2.0f};            // [%/kPa]  — |오차| ≤ kp_break_kpa 에서의 이득
    float kp_far{-1.0f};       // [%/kPa]  — 그 밖의 이득 (<0 이면 kp 와 동일)
    // 두 이득의 경계 [kPa]. 적분 밴드(band_kpa)와 **별개**다 — 둘을 같은 값으로
    // 묶었더니 밴드 밖에서 적분이 멈춘 채 비례항만 남아, 크래킹을 못 넘는 구간이
    // 교착에 빠졌다 (아래 band_kpa 주석 참조).
    float kp_break_kpa{3.0f};
    float ki{5.0f};            // [%/(kPa·s)] — |오차| ≤ kp_break_kpa (정착 구간)
    // 정착 구간 **밖**의 적분 이득. <0 이면 ki 와 동일.
    //
    // 상승 오버슛의 원인이 이것이었다. 실기 20260908_130406: 목표에 **도달한
    // 순간** 오차는 0 이라 P 항이 0 인데, micro 지령이 파킹 바이어스보다
    // 10 kPa 스텝에서 +7~14 %p, 20~50 kPa 스텝에서 +24~32 %p 높았다 — 전부
    // 접근 구간에서 쌓인 적분이다. 크래킹 위 27 %p 로 계속 채우니 오버슛이
    // 각각 +3.6~6.6 / +9.9~13.0 kPa 로 u_pid 에 그대로 비례했다.
    //
    // 이동 중에는 P 가 일하고 적분은 거의 쌓지 않는다. 적분의 역할은 도달한 뒤
    // 파킹 누설이 만드는 마지막 오차를 지우는 것이므로 정착 구간에서만 빠르게
    // 쌓으면 된다. (적분을 아예 끄는 밴드는 경계 밖 교착을 만들어 쓰지 않는다 —
    // ki_far 는 느리게라도 계속 쌓으므로 그 구멍이 없다.)
    float ki_far{-1.0f};       // [%/(kPa·s)]
    // [%·s/kPa] — **측정 미분**이다 (오차 미분이 아니다). Config::d_tau_s 로 거른다.
    // 오차로 미분하면 목표 계단이 그대로 미분돼 밸브를 때린다: 실기 20260914_180303
    // 에서 −55 kPa 계단의 첫 틱에 d_term 이 **330 %p** 로 튀어 명령이 상한에 박혔다.
    // 목표 계단은 제어할 대상이 아니라 그냥 새 동작점이므로 미분에서 뺀다.
    float kd{0.02f};
    float i_limit_pct{40.0f};  // 적분 누적 상한 [%] (양·음 대칭) — anti-windup

    // ── 적분 데드밴드 [kPa] ───────────────────────────────────────────────
    // 적분 입력에서 이만큼을 뺀다:  e_i = e − sign(e)·min(|e|, i_deadband_kpa)
    // 0 = 끔. 켜고 끄는 문턱이 아니라 **연속적으로 빼므로** 경계에서 튀지 않는다.
    //
    // 왜 필요한가 — 실기 20260908_153522 에서 대기압을 못 지켰다:
    //   목표가 대기압인데 오차가 0.2~0.7 kPa 로 남았다 (센서 분해능 0.25 kPa 의
    //   2~3 배, 밸브로는 분해할 수 없는 크기다). 적분이 그걸 지우려고 초당 1.2 %p
    //   씩 16 초간 걸어 올라가 micro 지령이 50 → 68% (크래킹 위 19 %p) 가 됐고,
    //   실제 크래킹을 넘는 순간 200 kPa 레일이 한 번에 들어와 **+52 kPa** 튀었다
    //   (ch3 +29, ch4 +22 도 같은 패턴).
    // 밸브가 만들 수 없는 정밀도를 적분에게 요구하면 반드시 이렇게 끝난다.
    // 데드밴드 밖의 진짜 오차(예: 3 kPa 누설)는 그대로 지운다.
    float i_deadband_kpa{0.5f};

    // 적분 밴드 [kPa], 0 = 끔 (**기본은 끔**). |오차| 가 이보다 크면 적분을 정지한다.
    //
    // 의도는 유량 제한 구간(실측 50 kPa 스텝: 레일 174 → 109 kPa 붕괴, 도달 3.3 s)의
    // windup 방지였다. 그런데 켜 보니 **경계 바로 밖이 교착**이 된다:
    //   |e| = band + ε 에서 비례항은 kp·band + kp_far·ε 로 작고, 그것이 크래킹을
    //   넘는 값(= 바이어스 margin, 5 %p)보다 작으면 유량이 0 인데 적분도 꺼져 있다.
    //   그 자리에서 압력이 영구히 멈춘다 — 기동 직후 목표가 대기압일 때 실제로
    //   대기압에 도달하지 못했다.
    // windup 은 실효 상한 기준 포화 판정(Input::u_limit_*)이 이미 정확히 막는다.
    // 그쪽은 "지령이 하드웨어 한계에 붙었을 때만" 멈추므로 이런 구멍이 없다.
    // 그래서 기본은 끔이고, 이 항은 특수한 경우를 위한 knob 으로만 남긴다.
    float band_kpa{0.0f};

    // ── 접근 속도 게이팅 [s], 0 = 끔 ──────────────────────────────────────
    // 적분 입력을 오차가 아니라 **이 시간 뒤에 남아 있을 오차**로 바꾼다:
    //
    //     e_pred = e + i_lead_s · de/dt      (de/dt 는 **측정에서만**, 목표 제외)
    //
    // 왜 필요한가 — 실기 20260914_180303, 음압 채널에 −55 kPa 계단:
    //   챔버(101)가 진공 레일(30)로 쏟아지며 110 kPa/s 로 움직였다. 그 0.5 초
    //   동안 오차가 계속 크니 적분이 ki_far·gs = 1.0×2.0 = 2.0 %/(kPa·s) 로
    //   쌓여 **i_limit 20 %p 를 꽉 채웠다.** 목표에 닿은 뒤에도 그 포화된 적분이
    //   micro 를 65 % 열어 둔 채 1 초를 더 빨아 **−11.9 kPa 오버슛**, 회복에 5 초.
    //   (같은 계단에서 레일이 +14 kPa 밀려 dp_micro 가 16 으로 읽히는 바람에
    //    gain_scale 이 상한 2.0 으로 튀어 ki 까지 두 배가 된 것도 겹쳤다.)
    //   그 0.5 초의 오차는 **플랜트가 이동 중이라 생긴 것**이지 보상해야 할
    //   정상상태 바이어스가 아니다. 쌓으면 그대로 오버슛이 된다.
    //
    // band_kpa 와 무엇이 다른가 — band_kpa 는 |오차| 로 끊어서, 유량이 0 인데
    // 오차만 큰 자리(경계 바로 밖)에서 교착에 빠졌다 (band_kpa 주석 참조).
    // 여기는 **속도**로 끊는다. 플랜트가 멈춰 있으면 de/dt = 0 이라 e_pred = e 로
    // 돌아가 그대로 적분한다 — 교착이 원리적으로 생기지 않는다.
    //
    // 크기: 접근이 이 시간 안에 끝날 만큼 빠르면 적분을 거의 멈춘다. 위 실측에서
    // 0.3 이면 접근 구간 내내 e_pred ≈ 0 이 된다.
    // 안전장치 두 가지: |e_pred| 는 |e| 를 절대 넘지 않고, 부호가 뒤집히면 0 이다
    // (적분을 반대로 밀지는 않는다 — 그건 미분항이 할 일이다).
    float i_lead_s{0.0f};

    // ── 공급 차압 게이팅 [kPa], 0 = 끔 ────────────────────────────────────
    // 그 방향에서 열릴 밸브의 차압이 이보다 작으면 적분을 멈춘다.
    //
    // 차압이 없으면 **밸브를 아무리 열어도 유량이 0** 이다. 그때 쌓는 적분은
    // 보상이 아니라 순수한 windup 이고, 공급이 돌아오는 순간 그대로 오버슛이 된다.
    //
    // 실기 20260915_142748, P+ 111→156 (45 kPa) 계단 3 회:
    //   챔버가 빨아들여 **레일이 190 → 125 로 무너지고 dp_micro 가 −1.7 까지**
    //   갔다. 3 초 넘게 유량이 0 인데 오차는 −30 이라, 적분이 i_limit 20 을
    //   꽉 채웠다. 공급이 돌아오자 오버슛 **+9.1** (같은 계단이 레일이 멀쩡할
    //   때는 +2.7 이었다).
    //
    // i_lead_s 로는 못 막는다 — 그쪽은 "빨리 접근 중이면 쉬어라" 인데, 공급이
    // 없어 **못 움직이는** 상황도 de/dt ≈ 0 이라 게이트가 통과시킨다.
    // 조건부 적분(u_limit 기준)으로도 못 막는다 — 하드웨어 밸브는 100 % 인데
    // 제어기 안의 u 는 상한(≈51)에 못 미쳐 "여유 있다" 로 본다.
    //
    // **micro(레일) 방향에만 건다.** atm 은 대기가 상대라 마르지 않는데, 대기로
    // 빼는 쪽은 차압이 곧 오차 자신(챔버 − 대기압)이다 — 목표가 대기압이면
    // 도착할수록 차압이 0 으로 가므로 문턱을 걸면 영영 못 내려간다.
    // 실측 20260915_143259 에서 그렇게 막혔다: 대기압 목표인데 적분이 +3.07 에
    // 얼어 챔버가 102.9~103.3 에 갇혔다 (게이팅 전에는 적분 −20 으로 atm 을
    // 80 % 열어 101.3 에 도달했다).
    //
    // 교착은 없다: 레일이 회복하면 dp 가 올라가 적분이 바로 다시 산다.
    // 3 kPa 근거 — 정상 운전의 dp 는 20~90 kPa 라 평소엔 걸리지 않는다.
    // 걸리는 것은 레일이 챔버까지 끌려온 구간뿐이다.
    float i_dp_min_kpa{0.0f};

    // ── 반대 부호 적분 누설 시정수 [s], 0 = 끔 ────────────────────────────
    // 적분이 **지금 필요한 방향과 반대** 이고 오차가 정착 구간(kp_break) 밖이면,
    // 그 적분은 직전 동작점의 유물이다. 이 시정수로 0 을 향해 흘려보낸다.
    //
    // 왜 i_reset_on_step 으로 안 되나 — 그쪽은 지령이 **점프**할 때만 본다.
    // 램프로 들어가면 매 틱 증가분이 문턱(1 kPa)보다 훨씬 작아 한 번도 안 걸린다.
    // 실기 20260916_152740, 시나리오 경계에서 4 kPa/s 로 111.3 까지 기울여 진입:
    //   t=160.7  지령 103.4  실측 101.4  i −16.7  atm 여유 +14.0  ← 배기 중
    //   t=162.7  지령 111.3  실측 101.4  i  −9.2  atm 여유  +0.8  ← 유지 시작
    //   램프 2 초 내내 atm 이 열린 채 압력이 101.4 에 붙어 있었고, 유지가 시작된
    //   뒤에도 적분이 부호를 넘기는 데 0.6 초가 더 걸려 3 초 유지 안에 못 들어왔다
    //   (최소 오차 2.12 kPa). 같은 목표라도 **계단**으로 들어간 구간은 리셋이
    //   작동해(−8.98 → +0.03) 곧바로 열렸다 — 차이가 정확히 이것이다.
    //   전체로 보면 오차 3 kPa 밖의 시간 중 양압 28.9 %, 음압 35.9 % 가
    //   반대 부호 적분에 잡혀 있었다 (최대 |i| 15.9 / 17.3).
    //
    // 왜 '버리기' 가 아니라 '누설' 인가 — 부호 반전으로 **즉시 0** 으로 만들면
    // 정착 구간에서 오차가 0 근처를 오갈 때마다 지워져 누설 보상이 사라진다
    // (i_reset_on_step_kpa 주석 참조). 그래서 두 가지를 같이 건다:
    //   · 정착 구간(|e| ≤ kp_break_kpa) 안에서는 **아무것도 하지 않는다**
    //   · 밖에서도 즉시 0 이 아니라 시정수로 흘린다 (계단을 만들지 않는다)
    // 0.3 s 면 위 램프 2 초 동안 −16.7 이 −0.03 까지 빠진다.
    float i_opp_leak_tau_s{0.0f};

    // ── 대기압 반대편 회수 부스트 ─────────────────────────────────────────
    // 챔버가 대기압의 **반대편**으로 끌려갔고(양압이 대기압 아래, 음압이 위)
    // 목표가 대기압이거나 그 너머면, atm 밸브 지령을 최소 이만큼은 연다 [%p].
    // 0 = 끔.
    //
    // 왜 따로 바닥을 까는가 — 이 구간에서는 오차와 구동 차압이 **같은 수**다
    // (둘 다 |챔버 − 대기압|). 그래서 P 항도 차압도 같이 0 으로 수렴해 마지막
    // 몇 kPa 가 한없이 느려진다. 실측 20260916_161632: 양압 챔버가 대기압
    // −0.5 아래에 런당 32.6~36.9 초(최저 93.28 kPa), 음압은 +0.5 위에
    // 18~20 초(최고 102.99) 머물렀다 — 그동안 atm 은 100 % 열려 있었으니
    // 라우팅은 맞았고 **여는 양이 모자랐다.** 예전 로그(20260915_143259)에서
    // 이 구간을 끝낸 것도 P 가 아니라 적분이 −20 까지 차올라 atm 을 80 %
    // 열어서였다 — 그 20 %p 를 몇 초 걸려 쌓는 대신 즉시 준다.
    //
    // 왜 크게 열어도 안전한가 — atm 밸브는 챔버를 대기압까지만 데려가고
    // **거기서 스스로 멈춘다.** 목표가 대기압이거나 그 너머일 때는 아무리 활짝
    // 열어도 목표를 지나칠 수 없다. 게인을 못 올리게 막는 평소의 오버슛 제약이
    // 이 구간에만은 물리적으로 적용되지 않는다. 그래서 목표가 챔버와 대기압
    // **사이**에 있으면(그때는 지나칠 수 있다) 이 바닥을 걸지 않는다.
    float atm_boost_pct{0.0f};

    // ── 레퍼런스 스텝에서 적분 리셋 ───────────────────────────────────────
    // 목표가 이 값보다 크게 바뀌면 적분을 0 으로 놓는다 [kPa]. 0 = 끔.
    //
    // 대기압에 오래 머물면 파킹 누설과 싸우느라 적분이 한쪽 끝(예: 배기 −40%)까지
    // 차 있다. 그 상태에서 위로 스텝이 들어오면 적분이 **반대 방향**이라 먼저
    // 풀려야 하고, 그동안 밸브가 안 열린다 (ki=3, 오차 30 kPa 이면 0 을 지나는
    // 데만 ≈0.4 s). 그게 "대기압에 오래 있다가 스텝을 주면 늦게 출발하는" 이유다.
    //
    // 목표가 바뀌는 순간의 적분은 **직전 동작점의 유물**이므로 버리는 것이 맞다.
    // 새 동작점의 누설 보상은 도달한 뒤 다시 쌓인다.
    // 오차 부호가 뒤집힐 때 리셋하는 방식은 쓰지 않는다 — 정착 구간에서 오차가
    // 0 근처를 오가면 매번 리셋돼 누설 보상 자체가 사라진다.
    float i_reset_on_step_kpa{2.0f};

    // ── 동작점(차압)에 따른 이득 보정 ────────────────────────────────────
    // 0 = 끔. >0 이면 이 차압을 기준으로 kp·kp_far·ki 를 함께 스케일한다:
    //
    //     scale = clamp(gain_dp_ref_kpa / 현재 차압, gain_scale_min, gain_scale_max)
    //
    // 유량은 차압에 거의 비례하므로, 같은 지령이라도 차압이 작으면 플랜트 이득이
    // 작아져 굼떠진다. 실측 20260910_164518 (레일 196, 계단 시험):
    //     동작점 120 (micro 차압 78) → 90% 도달 0.40 s
    //     동작점 160 (micro 차압 40) → 90% 도달 0.81 s     ← 정확히 2배 느리다
    // 차압으로 나눠 주면 동작점이 달라져도 응답이 비슷해진다.
    //
    // 방향마다 차압이 다르다 (양압 micro 는 레일−챔버, atm 은 챔버−대기).
    // 그래서 그 순간 열릴 밸브의 차압을 쓴다 (Input::dp_micro_kpa / dp_atm_kpa).
    float gain_dp_ref_kpa{0.0f};
    float gain_scale_min{0.5f};
    float gain_scale_max{2.0f};

    // ── 레퍼런스 속도 피드포워드 [%p per (kPa/s)] ─────────────────────────
    // 0 = 끔.  u_ff = kv · dP_ref/dt  (차압 보정 gs 를 같이 곱한다)
    //
    // 왜 필요한가 — 사인을 따라가는 데 필요한 지령은 **오차가 아니라 목표의
    // 속도**에 비례한다 (유량 ∝ 개도, dP/dt ∝ 유량). PI 는 그 지령을 적분으로만
    // 만들 수 있어서 반드시 오차가 먼저 생겨야 한다.
    // 방향이 바뀌는 순간이 가장 나쁘다: 필요한 지령이 한쪽 밸브의 데드존에서
    // 반대쪽 밸브의 데드존까지 통째로 건너가야 하는데, 그 구간에서 오차는 0
    // 근처라 적분이 ki·e 로 느리게만 움직인다.
    // 실측 20260911_170834 (사인 진폭 10 kPa, 주기 40 s): 반전 후 3~4 초 동안
    // 오차가 −3.0 ~ +2.4 kPa 까지 벌어진 뒤 한 번에 되돌아왔다. 12채널 전부.
    //
    // 적분 리셋으로는 이걸 제대로 못 고친다. 반전 시점의 적분은 "직전 동작점의
    // 유물" 이 아니라 **데드존 표의 오차를 보상하고 있는 실값**이다 (같은 로그에서
    // 9분 동안 필요한 지령이 micro/atm 양쪽 다 3~5 %p 씩 밀렸다). 0 으로 버리면
    // 그 보상까지 잃고 새 과도가 생긴다. 속도 항을 직접 넣는 것이 맞다.
    //
    // 크기 잡는 법: kv ≈ 1 / (플랜트 기울기 [kPa/s per %p]).
    // 이 동작점(레일 145, 챔버 110~130)의 실측 회귀는 양압 2.6, 음압 1.9 인데
    // 데드존 표의 차압 의존이 섞여 R² 0.01~0.23 으로 신뢰도가 낮다. 개루프
    // 데드존 측정에서 환산한 값(양압 상승 ≈1.0)과의 중간에서 출발한다.
    float kv{0.0f};
  };

  // ── 채널 고정 설정 (생성 시 한 번) ────────────────────────────────────────
  struct Config {
    int   can_board_id{4};     // 물리 보드 ID (1-based). PWM 슬롯 = (id-1)*3 + v
    int   global_id{0};        // 채널 gid. 목표압 배열 mpc_ref_kpa_ 의 인덱스
    bool  is_positive{true};   // true = 양압 챔버, false = 음압 챔버

    float u_min_pct{0.0f};     // 명령 하한 [%]
    float u_max_pct{100.0f};   // 명령 상한 [%]

    // PID 게인을 **방향별로** 둔다. 밸브가 방향마다 다른 물리를 갖기 때문이다.
    //   g_up   : 압력을 올리는 방향 (양압 채널은 micro, 음압 채널은 atm)
    //   g_down : 압력을 내리는 방향 (양압 채널은 atm,   음압 채널은 micro)
    //
    // 왜 필요한가 — 실측 유효면적 (config/valve_params.yaml):
    //   양압 ch0~5: micro 0.03226 / atm 0.00600 mm²  → 채우는 밸브가 **5.4배**
    //   음압 ch6~11: micro 0.01850 / atm 0.01500 mm² → 1.2배 (거의 대칭)
    // 방향에 무관하게 같은 % 를 내면 양압 채널은 **올리는 방향 루프 이득이 5.4배**
    // 높다. 가속은 세고 제동은 약해 목표를 지나치고, 5.4배 작은 밸브로 되돌리므로
    // 왕복이 길어진다 — 실기 20260907_213052 에서 양압만 도달 후 p-p 6~15 kPa 로
    // 흔들렸고 (음압은 1.7) 오버슛도 양압만 났다.
    // 여기에 구동압 비대칭도 겹친다: 질량유량 ∝ 상류 절대압이라 양압은 레일
    // 181 kPa 로 밀 수 있는데 음압은 상류가 챔버 자신(≤101 kPa)이다.
    // 실측 최대 변화율 양압 +132 / 음압 −90 kPa/s.
    Gains g_up{};
    Gains g_down{};

    // ── 레퍼런스 속도 추정 ────────────────────────────────────────────────
    // 목표는 10 Hz 계단으로 들어오는데 제어는 500 Hz 다. 그대로 미분하면
    // 100 ms 마다 0.11/0.002 ≈ 55 kPa/s 스파이크가 나오므로 반드시 저역 통과다.
    // 사인 0.025 Hz 에 tau 0.3 s 가 주는 위상 지연은 2.7° 뿐이다.
    float ref_rate_tau_s{0.3f};   // 0 = 필터 끔 (권장하지 않는다)
    // 측정 미분(kd 항·i_lead_s 게이팅 공용)의 저역통과 시정수 [s]. 0 = 필터 끔.
    // 챔버압 센서 LSB 가 0.25 kPa 이고 루프가 500 Hz 라, 걸지 않으면 미분 잡음만
    // ±125 kPa/s 다. 0.02 s 면 잡음은 25 배 줄고 계단 응답(0.5 s)은 안 흐려진다.
    float d_tau_s{0.02f};

    // ── 대기압 판정 여유 [kPa] ────────────────────────────────────────────
    // 챔버가 대기압의 **어느 쪽에 있는지**로 밸브를 고르므로(아래 참조), 경계에서
    // 센서 잡음(LSB 0.25 kPa)에 따라 밸브가 번갈아 열리면 안 된다. 이만큼
    // 확실히 넘어가야 "반대편" 으로 본다.
    // 재라우팅은 **atm 이 목표까지 갈 수 있을 때만** 한다 — atm 은 대기압에서
    // 멈추므로, 목표가 그 너머면 어차피 레일이 필요하다. 이 조건이 없으면 음압이
    // 망가진다 (목표가 대기압 한참 아래인데 차압 1.5 kPa 로 빼려 든다).
    float atm_margin_kpa{0.5f};
    float atm_kpa{101.325f};      // 기준 대기압
    float ff_limit_pct{15.0f};    // 피드포워드 항 절대값 상한 [%p]
  };

  // ── 매 틱 입력 ────────────────────────────────────────────────────────────
  struct Input {
    // ★ 이 채널의 목표 압력 [kPa abs].
    //   control_mode 0 : RefTcpServer/RefTcpClient 가 받은 값이 그대로 온다
    //   control_mode 1 : 위치 PID 가 만든 값
    //   control_mode 2 : PressureRefGen 이 힘 배분으로 만든 값
    float P_ref_kpa{101.325f};

    float P_meas_kpa{101.325f};      // 챔버 압력 (LPF 통과, ≈18 ms 지연)
    float P_meas_raw_kpa{101.325f};  // 챔버 압력 (필터 전, 즉각·잡음 있음)

    // 이 채널이 쓰는 상류/하류 압력
    float P_supply_kpa{101.325f};    // micro 상류 (양압=P_line_pos, 음압=P_line_neg)
    float P_macro_kpa{101.325f};     // 양압 macro 상류 (탱크)
    float P_macro_neg_kpa{101.325f}; // 음압 macro 상류
    float P_atm_kpa{101.325f};       // 대기압 (atm 밸브의 반대쪽)

    float volume_m3{1.0e-5f};        // 이번 틱 챔버 부피 (엔코더 각도에서 계산)
    float prev_volume_m3{1.0e-5f};   // 직전 틱 부피

    float rail_rate_kpa_s{0.0f};     // 이 채널이 붙은 레일의 압력 변화율 [kPa/s]

    // ── 이 틱에 실제로 쓸 수 있는 지령 폭 [%] ────────────────────────────
    // 크래킹 바이어스는 제어기 **밖**(Controller)에서 더해진다. 그래서 하드웨어가
    // 받는 값은 (임계 − margin) + u 이고 100 에서 잘린다 — 즉 이 제어기가 낼 수
    // 있는 u 의 실효 상한은 100 이 아니라 100 − (임계 − margin) 이다 (micro 는
    // 임계 51% 근처이므로 ≈54).
    //
    // anti-windup 이 이 값을 봐야 한다. 100 을 기준으로 포화를 판정하면 하드웨어가
    // 이미 활짝 열린 뒤에도 "아직 여유가 있다" 고 보고 적분을 계속 쌓는다
    // (20260907_204249 의 도달 후 오버슛 원인).
    // Controller 가 매 틱 채운다. 채우지 않으면 100 = 예전 동작.
    float u_limit_up_pct{100.0f};    // micro 방향 (u > 0)
    float u_limit_down_pct{100.0f};

    // 이 채널 두 밸브의 현재 차압 [kPa] (상류 − 하류). Controller 가 채운다.
    // Gains::gain_dp_ref_kpa 가 켜져 있을 때만 쓴다.
    float dp_micro_kpa{0.0f};
    float dp_atm_kpa{0.0f};  // atm 방향   (u < 0)

    float dt_sec{0.002f};            // 실측 제어 주기 [s]
    float t_sec{0.0f};               // 노드 기동 후 경과 시간 [s] (틱 기반)

    // 과압 세이프티가 래치된 상태. 이 틱의 명령은 Controller 가 무시하고 밸브를
    // 강제 전개하므로, 적분항을 멈춘다 (내 탓이 아닌 오차를 쌓지 않는다).
    bool  safety_latched{false};
  };

  // ── 매 틱 출력 ────────────────────────────────────────────────────────────
  struct Output {
    // 밸브 개도 명령 [%], 순서 {micro, macro, atm}. 0 = 폐쇄.
    std::array<float, N_VALVE> u_pct{{0.0f, 0.0f, 0.0f}};
  };

  explicit PressureCtrl(const Config& cfg);

  // ★ 목표 압력이 들어오고 제어 신호가 나가는 함수.
  //   기본 PID + anti-windup 만 한다. 데드밴드·미분 필터·명령 변화율 제한·크래킹
  //   하한·macro 부스트 같은 것은 없다 — 필요하면 여기에 얹는다.
  //
  // 채널마다 인스턴스가 하나이고, 매 제어 틱(기본 500 Hz)에 정확히 한 번 불린다.
  // 활성 채널들은 ThreadPool 에서 **병렬로** 불리므로 자기 인스턴스의 멤버만
  // 만진다 (전역·정적 가변 상태 없음).
  Output compute(const Input& in);

  // 내부 상태(적분·직전 오차·직전 명령) 초기화. 모드 전환·재기동 시.
  void reset();

  const Config& cfg() const { return cfg_; }
  Config&       cfg_mutable() { return cfg_; }
  const Output& last_output() const { return last_; }

  // 이번 틱에 쓰인 게인 (방향에 따라 갈린다)
  const Gains& gains_used() const { return (err_ >= 0.0f) ? cfg_.g_up : cfg_.g_down; }

  // 진단용 — 이 채널이 지금 무슨 일을 하고 있는지 한 줄로 보기 위한 값들.
  //
  // 항을 **따로** 남기는 이유: 로그에 밸브 지령(u_hw)만 있으면 제어기 내부를
  // 역산해야 하는데, u_hw = 데드존표(dp) − 여유 + u_pid 라 표가 틀리면 그 오차가
  // 전부 "적분" 으로 보이고 분해가 불가능하다. 실제로 20260911_180020 을 역산했을
  // 때 복원된 적분이 한계(±8)를 넘어 나왔다 — 표 오차가 섞였다는 뜻이다.
  // 항을 그대로 찍으면 적분 포화·피드포워드 기여·표 오차를 각각 분리할 수 있다.
  float integ_pct() const { return integ_; }   // 적분 누적 [%]
  float ref_rate_kpa_s() const { return dref_filt_; }  // 목표압 변화율 (필터 후)
  float error_kpa() const { return err_; }     // 이번 틱 오차 (P_ref − P_meas)
  float u_pid_pct() const { return u_last_; }  // 합산 후 클램프까지 끝난 지령 [%]
  float p_term_pct() const { return p_last_; }
  float i_term_pct() const { return integ_; }
  float d_term_pct() const { return d_last_; }
  float ff_term_pct() const { return ff_last_; }
  float gain_scale() const { return gs_last_; }      // 차압 이득 보정 배율
  // 이번 틱에 적분이 멈췄거나 한계에 붙었는가 — 0 없음 / 1 클램프 / 2 조건부정지
  int   integ_state() const { return isat_last_; }

  // 내부 %명령 → 보드 PWM.
  //   반환 순서는 **보드 슬롯 순서** {v1=micro, v2=atm, v3=macro} 이고
  //   스케일은 100% → 4095 다. Controller 가 zoh_[(board-1)*3 + k] 에 그대로 넣는다.
  static std::array<uint16_t, N_VALVE> to_pwm(const Output& out);

private:
  Config cfg_;
  Output last_{};        // 직전 틱 명령 (진단용)

  // PID 상태
  float integ_{0.0f};    // 적분 누적 [%]
  float err_{0.0f};      // 이번 틱 오차 (P_ref − P_meas) [kPa] — 진단용
  float ref_prev_{0.0f}; // 직전 틱 목표압 [kPa] — 스텝 감지용
  float dref_filt_{0.0f}; // 저역 통과한 목표압 변화율 [kPa/s] — 피드포워드용
  // 진단용 항별 스냅샷 (매 틱 갱신, 제어에는 쓰지 않는다)
  float u_last_{0.0f}, p_last_{0.0f}, d_last_{0.0f}, ff_last_{0.0f};
  float gs_last_{1.0f};
  int   isat_last_{0};
  float e_prev_{0.0f};   // 직전 틱 오차 (부호 정규화 후) — 진단용
  float pm_prev_{0.0f}; // 직전 틱 측정압 [kPa] — 측정 미분용
  bool  wrong_side_{false};  // 직전 틱에 챔버가 대기압 반대편에 있었나
  float de_filt_{0.0f}; // 저역 통과한 **측정 기인** de/dt [kPa/s] (부호 정규화 후)
  bool  first_{true};
};
