if __name__ == '__main__':
    out = 'results'
    os.makedirs(out, exist_ok=True)

    results = []
    best_label, best_data, best_rmse = None, None, 1e9

    print(f"{'Label':<10} {'RMSE_pos':>10} {'RMSE_neg':>10}  {'total':>10}")
    print('-' * 46)

    for row in GAINS:
        lbl, pp, pn = make_params(row)
        d = run(pp, pn)
        results.append((lbl, d))

        ep = rmse(d['P_pos'], d['rp'], d['t'])
        en = rmse(d['P_neg'], d['rn'], d['t'])
        total = ep + en
        print(f"{lbl:<10} {ep:>10.3f} {en:>10.3f}  {total:>10.3f}")

        if total < best_rmse:
            best_rmse, best_label, best_data = total, lbl, d

    print(f"\nBest: {best_label}")

    # Save best result
    save_csv(best_data, f'{out}/sim_result_best.csv')
    plot(best_data,
         f'Pneumatic Sim  [{best_label}]  ch0(+) + ch6(-)  –  20 s',
         f'{out}/sim_result_best.png')

    # Save comparison
    plot_comparison(results, f'{out}/sim_comparison.png')

    # Also save all CSVs
    for lbl, d in results:
        save_csv(d, f'{out}/sim_{lbl}.csv')

    print(f"\nOutput files:")
    for f in sorted(os.listdir(out)):
        size = os.path.getsize(f'{out}/{f}')
        print(f"  {out}/{f}  ({size/1024:.1f} KB)")

    # Diagnostics on best result
    d  = best_data
    t  = np.array(d['t'])
    Pp = np.array(d['P_pos']); rp = np.array(d['rp'])
    Pn = np.array(d['P_neg']); rn = np.array(d['rn'])

    def settling(t, P, t_step, r_target, tol=2.0):
        idx = np.where(t > t_step)[0]
        for i in idx:
            if all(abs(P[i:i+50] - r_target) < tol):
                return t[i] - t_step
        return float('nan')

    print(f"\nSettling time (±2 kPa, from step edge):")
    sp1 = settling(t, Pp, 2.0, 150.0)
    sn1 = settling(t, Pn, 2.0,  85.0)
    sp2 = settling(t, Pp, 6.0, 200.0)
    sn2 = settling(t, Pn, 6.0,  72.0)
    sp3 = settling(t, Pp,10.0, 130.0)
    sn3 = settling(t, Pn,10.0,  90.0)
    print(f"  Positive  101→150 kPa (t=2s): {sp1:.3f} s")
    print(f"  Negative  101→85  kPa (t=2s): {sn1:.3f} s")
    print(f"  Positive  150→200 kPa (t=6s): {sp2:.3f} s")
    print(f"  Negative   85→72  kPa (t=6s): {sn2:.3f} s")
    print(f"  Positive  200→130 kPa (t=10s): {sp3:.3f} s")
    print(f"  Negative   72→90  kPa (t=10s): {sn3:.3f} s")

    mask_sine = t >= 14.0
    ep_sine = abs(Pp[mask_sine] - rp[mask_sine])
    en_sine = abs(Pn[mask_sine] - rn[mask_sine])
    rmse_ep = np.sqrt(np.mean(ep_sine**2))
    rmse_en = np.sqrt(np.mean(en_sine**2))
    print(f"\nSine tracking (t=14-20s):")
    print(f"  Positive: RMSE={rmse_ep:.3f} kPa  peak_err={ep_sine.max():.3f} kPa")
    print(f"  Negative: RMSE={rmse_en:.3f} kPa  peak_err={en_sine.max():.3f} kPa")
