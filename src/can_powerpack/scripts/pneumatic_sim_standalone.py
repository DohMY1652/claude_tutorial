#!/usr/bin/env python3
"""
Standalone pneumatic control simulation (no ROS2 required).
Paper: "Modeling and RL-Based Control of Simultaneous Positive and Negative
        Pressure Generation in Pneumatic Systems"

Physics:  mirrors PneumaticSim.cpp (valve flow + ideal gas)
Control:  mirrors compute_input_reference() in Controller.cpp (feedforward + integral)
Channels: ch0 (positive, gid=0, board 5) + ch6 (negative, gid=6, board 11)
"""

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import csv, os

# ── Physical constants (same as Controller.cpp) ──────────────────────────────
RGAS    = 287.0       # J/(kg·K)
TEMP_K  = 293.15      # K
LPM2KG  = 0.0002155   # kg/s per LPM  (empirical, fitted to hardware)
ATM_KPA = 101.325     # kPa

# ── Supply lines ─────────────────────────────────────────────────────────────
P_LINE_POS   = 400.0  # kPa  positive supply
P_LINE_NEG   =  50.0  # kPa  suction line
P_LINE_MACRO = 400.0  # kPa  macro supply
P_MACRO_NEG  =  50.0  # kPa  negative macro outlet

# ── Integration ──────────────────────────────────────────────────────────────
DT        = 0.002     # 500 Hz control loop
N_SUB     = 10        # Euler sub-steps per tick (0.2 ms)
T_TOTAL   = 55.0      # seconds (extended for low-frequency sine evaluation)

# ─────────────────────────────────────────────────────────────────────────────
# BiPAM Force Model
# Source: "Cooperative antagonistic mechanism driven by bidirectional pneumatic
#          artificial muscles for soft robotic joints"
#          Park, J.H., Kim, K., Gong, Y.J., et al.
#          Mechatronics 97, 2023. DOI: 10.1016/j.mechatronics.2023.103099
#
# Derivation: virtual work principle  →  F = P_gauge × (dV / dL)
#
#   Positive pressure (P > P_atm):  bellows contracts axially.
#     V(L) = π r_m² L   →   dV/dL = π r_m²
#     F_pos = (P − P_atm) × 1e3 × π r_m²                       [N]
#
#   Negative pressure (P < P_atm):  inner deformable structure extends.
#     V(L) = π r_i² L   →   dV/dL = π r_i²
#     F_neg = (P_atm − P) × 1e3 × π r_i²                       [N]
#
#   Length-dependent correction (geometric nonlinearity):
#     F(ε) = F₀ × (1 + c₁ε + c₂ε²)
#     ε_pos = (L₀ − L) / L₀  ∈ [0, 0.751]   (contraction strain, paper max 75.1 %)
#     ε_neg = (L − L₀)  / L₀ ∈ [0, 4.021]   (extension  strain, paper max 402.1 %)
#
# Effective radii are back-calculated from the paper's peak force data:
#   F_pos_max = 124.46 N  @ ΔP_pos = P_LINE_POS − ATM = 298.7 kPa
#     → r_m   = sqrt(124.46 / (298675 × π)) ≈ 11.5 mm
#   F_neg_max = 122.80 N  @ ΔP_neg = ATM − P_LINE_NEG =  51.3 kPa
#     → r_i   = sqrt(122.80 / ( 51325 × π)) ≈ 27.6 mm
#
# Calibrate _BIPAM geometry and polynomial coefficients from the paper's
# measured force–stroke curves before use in real hardware.
# ─────────────────────────────────────────────────────────────────────────────

_BIPAM = dict(
    L0          = 0.15,       # m   max extension length per chamber (50 mm dia spec)
    r_m         = 0.025,      # m   effective radius = 50 mm / 2   (positive pressure)
    r_i         = 0.025,      # m   effective radius = 50 mm / 2   (negative pressure)
    # Polynomial correction: F(ε)/F₀ = 1 + c₁ε + c₂ε²
    # Positive: force decreases as bellows approaches full contraction
    c_pos       = (-0.80, 0.30),
    # Negative: force grows slightly then flattens as inner tube fully extends
    c_neg       = ( 0.50, -0.10),
    eps_max_pos = 0.751,      # clamp contraction strain to paper limit
    eps_max_neg = 4.021,      # clamp extension  strain to paper limit
)


def bipam_force_pos(P_kPa, L_m=None):
    """
    BiPAM contraction force [N] generated by positive (above-atm) pressure.

    P_kPa : absolute chamber pressure [kPa]
    L_m   : current actuator length [m]; None → skip length correction

    Returns force in the contraction direction (≥ 0).
    """
    dP = max(0.0, P_kPa - ATM_KPA) * 1e3       # Pa gauge
    F0 = dP * np.pi * _BIPAM['r_m'] ** 2        # [N]
    if L_m is None or F0 == 0.0:
        return F0
    eps = np.clip((_BIPAM['L0'] - L_m) / _BIPAM['L0'], 0.0, _BIPAM['eps_max_pos'])
    c1, c2 = _BIPAM['c_pos']
    return max(0.0, F0 * (1.0 + c1 * eps + c2 * eps ** 2))


def bipam_force_neg(P_kPa, L_m=None):
    """
    BiPAM extension force [N] generated by negative (below-atm) pressure.

    P_kPa : absolute chamber pressure [kPa]
    L_m   : current actuator length [m]; None → skip length correction

    Returns force in the extension direction (≥ 0).
    """
    dP = max(0.0, ATM_KPA - P_kPa) * 1e3        # Pa gauge (magnitude)
    F0 = dP * np.pi * _BIPAM['r_i'] ** 2         # [N]
    if L_m is None or F0 == 0.0:
        return F0
    eps = np.clip((L_m - _BIPAM['L0']) / _BIPAM['L0'], 0.0, _BIPAM['eps_max_neg'])
    c1, c2 = _BIPAM['c_neg']
    return max(0.0, F0 * (1.0 + c1 * eps + c2 * eps ** 2))


def bipam_net_force(P_pos_kPa, P_neg_kPa, L_m=None):
    """
    Series cooperative net force [N].

    Positive BiPAM (ch0) and negative BiPAM (ch6) are connected in series
    and act in the same direction.  Positive return = output direction.

    P_pos_kPa : ch0 absolute pressure [kPa]
    P_neg_kPa : ch6 absolute pressure [kPa]
    L_m       : actuator length [m] (shared geometric axis)
    """
    return bipam_force_pos(P_pos_kPa, L_m) + bipam_force_neg(P_neg_kPa, L_m)


# ─────────────────────────────────────────────────────────────────────────────
# Physics
# ─────────────────────────────────────────────────────────────────────────────

def calc_flow(u_pct, P_in, P_out, k0, k1, k2):
    """Valve flow [LPM].  flow = (k0*Pin + k1*u - k2)*sqrt(2*(Pin-Pout)*Pin)"""
    u_pct = max(0.0, min(100.0, u_pct))
    if P_in <= P_out:
        return 0.0
    root = (2.0 * (P_in - P_out) * P_in) ** 0.5
    return max(0.0, min(100.0, (k0 * P_in + k1 * u_pct - k2) * root))

def dPdt(P_now, u_mi, u_at, u_ma, k0, k1, k2, V, is_pos):
    """Returns dP/dt [kPa/s]."""
    if is_pos:
        net = ( calc_flow(u_mi, P_LINE_POS,   P_now, k0, k1, k2)
              + calc_flow(u_ma, P_LINE_MACRO,  P_now, k0, k1, k2)
              - calc_flow(u_at, P_now,         ATM_KPA, k0, k1, k2) )
    else:
        net = ( calc_flow(u_at, ATM_KPA,       P_now, k0, k1, k2)
              - calc_flow(u_mi, P_now,         P_LINE_NEG,  k0, k1, k2)
              - calc_flow(u_ma, P_now,         P_MACRO_NEG, k0, k1, k2) )
    return (RGAS * TEMP_K / V) * LPM2KG * net / 1000.0

# ─────────────────────────────────────────────────────────────────────────────
# Controller  (mirrors compute_input_reference in Controller.cpp)
# ─────────────────────────────────────────────────────────────────────────────

def compute_uref(P_now, P_ref, k0, k1, k2, V, is_pos,
                 TC, ki_mi, ki_ma, ki_at, macro_thr, integral, dt):
    """
    Feedforward + integral.
    Returns (u_mi, u_ma, u_at, new_integral).
    Mirrors compute_input_reference() including sign-flip & anti-windup reset.
    """
    err = P_ref - P_now
    # Integral update with anti-windup reset (mirrors Controller.cpp line 319-331)
    # Positive: intg += err*dt,  reset when sign(err) != sign(intg)
    # Negative: intg -= err*dt,  reset when sign(err) == sign(intg)
    if is_pos:
        if (err > 0 and integral < 0) or (err < 0 and integral > 0):
            integral = 0.0
        intg = max(-1000.0, min(1000.0, integral + err * dt))
    else:
        if (err > 0 and integral > 0) or (err < 0 and integral < 0):
            integral = 0.0
        intg = max(-1000.0, min(1000.0, integral - err * dt))

    # desired mass flow [LPM]
    P_dot = err * 1000.0 / max(1e-3, TC)          # Pa/s
    m_dot = P_dot * V / (RGAS * TEMP_K) / LPM2KG  # LPM

    u_mi = u_ma = u_at = 0.0

    def inv_valve(flow_req, P_in, P_out):
        """Invert calc_flow to get required u."""
        denom = (2.0 * P_in * max(1e-3, P_in - P_out)) ** 0.5
        return (abs(flow_req) / max(1e-9, denom) + k2 - k0 * P_in) / max(1e-9, k1)

    if is_pos:
        if m_dot > 0:                            # fill
            u_mi = inv_valve(m_dot, P_LINE_POS,  P_now) + ki_mi * intg
            if abs(err) >= macro_thr:
                u_ma = inv_valve(m_dot, P_LINE_MACRO, P_now) + ki_ma * intg
        else:                                    # exhaust
            u_at = inv_valve(m_dot, P_now, ATM_KPA) + ki_at * abs(intg)
    else:
        if m_dot < 0:                            # exhaust (decrease P toward suction)
            u_mi = inv_valve(m_dot, P_now, P_LINE_NEG) + ki_mi * intg
            if abs(err) >= macro_thr:
                u_ma = inv_valve(m_dot, P_now, P_MACRO_NEG) + ki_ma * intg
        else:                                    # fill (increase P toward atm)
            u_at = inv_valve(m_dot, ATM_KPA, P_now) + ki_at * abs(intg)

    clip = lambda x: max(0.0, min(100.0, x))
    return clip(u_mi), clip(u_ma), clip(u_at), intg

# ─────────────────────────────────────────────────────────────────────────────
# Reference trajectory
# ─────────────────────────────────────────────────────────────────────────────

def reference(t):
    """
    ch0 (positive): 0-2s hold atm, 2-6s step 150, 6-10s step 200,
                    10-14s step 130, 14-20s sine 165+35*sin(2π(t-14)/4)
    ch6 (negative): 0-2s hold atm, 2-6s step 85, 6-10s step 72,
                    10-14s step 90,  14-20s sine 80+8*sin(2π(t-14)/4)
    """
    # Sine starts smoothly from the previous step level (no discontinuity at t=14)
    if t < 2.0:
        rp, rn = ATM_KPA, ATM_KPA
    elif t < 6.0:
        rp, rn = 150.0, 85.0
    elif t < 10.0:
        rp, rn = 200.0, 72.0
    elif t < 14.0:
        rp, rn = 130.0, 90.0
    else:
        # Center chosen so sine(0)=0 means ref starts at 130 / 90 (no jump)
        phase = 2.0 * np.pi * (t - 14.0) / 20.0   # 0.05 Hz  (was 0.25 Hz)
        rp = 130.0 + 35.0 * np.sin(phase)           # 95 ~ 165 kPa
        rn =  90.0 -  8.0 * np.sin(phase)           # 82 ~ 98 kPa
    return rp, rn

# ─────────────────────────────────────────────────────────────────────────────
# Simulation runner
# ─────────────────────────────────────────────────────────────────────────────

def run(params_pos, params_neg):
    """
    params: dict with keys k0,k1,k2,volume_m3,TC,ki_mi,ki_ma,ki_at,macro_thr
    Returns arrays dict.
    """
    N  = int(T_TOTAL / DT)
    dt_sub = DT / N_SUB

    def unpack(p):
        return (p['k0'], p['k1'], p['k2'], p['volume_m3'],
                p['TC'], p['ki_mi'], p['ki_ma'], p['ki_at'], p['macro_thr'])

    k0p,k1p,k2p,Vp,TCp,kmi_p,kma_p,kat_p,mt_p = unpack(params_pos)
    k0n,k1n,k2n,Vn,TCn,kmi_n,kma_n,kat_n,mt_n = unpack(params_neg)

    P_pos = ATM_KPA; P_neg = ATM_KPA
    int_pos = int_neg = 0.0

    t_arr = np.empty(N); rp_arr = np.empty(N); rn_arr = np.empty(N)
    P_pos_arr = np.empty(N); P_neg_arr = np.empty(N)
    umi_p = np.empty(N); uma_p = np.empty(N); uat_p = np.empty(N)
    umi_n = np.empty(N); uma_n = np.empty(N); uat_n = np.empty(N)
    F_pos_arr = np.empty(N); F_neg_arr = np.empty(N); F_net_arr = np.empty(N)

    for k in range(N):
        t = k * DT
        rp, rn = reference(t)

        u_mi_p, u_ma_p, u_at_p, int_pos = compute_uref(
            P_pos, rp, k0p,k1p,k2p,Vp, True,
            TCp, kmi_p, kma_p, kat_p, mt_p, int_pos, DT)
        u_mi_n, u_ma_n, u_at_n, int_neg = compute_uref(
            P_neg, rn, k0n,k1n,k2n,Vn, False,
            TCn, kmi_n, kma_n, kat_n, mt_n, int_neg, DT)

        for _ in range(N_SUB):
            dp = dPdt(P_pos, u_mi_p, u_at_p, u_ma_p, k0p,k1p,k2p,Vp, True)
            dn = dPdt(P_neg, u_mi_n, u_at_n, u_ma_n, k0n,k1n,k2n,Vn, False)
            P_pos = max(50.0,  min(800.0, P_pos + dp * dt_sub))
            P_neg = max(10.0,  min(110.0, P_neg + dn * dt_sub))

        t_arr[k]=t; rp_arr[k]=rp; rn_arr[k]=rn
        P_pos_arr[k]=P_pos; P_neg_arr[k]=P_neg
        umi_p[k]=u_mi_p; uma_p[k]=u_ma_p; uat_p[k]=u_at_p
        umi_n[k]=u_mi_n; uma_n[k]=u_ma_n; uat_n[k]=u_at_n
        F_pos_arr[k] = bipam_force_pos(P_pos)
        F_neg_arr[k] = bipam_force_neg(P_neg)
        F_net_arr[k] = bipam_net_force(P_pos, P_neg)

    return dict(t=t_arr, rp=rp_arr, rn=rn_arr,
                P_pos=P_pos_arr, P_neg=P_neg_arr,
                umi_p=umi_p, uma_p=uma_p, uat_p=uat_p,
                umi_n=umi_n, uma_n=uma_n, uat_n=uat_n,
                F_pos=F_pos_arr, F_neg=F_neg_arr, F_net=F_net_arr)

