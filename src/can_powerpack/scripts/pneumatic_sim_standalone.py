def plot_comparison(results, path):
    """Overlay multiple gain sets on one figure."""
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    colors = [f'C{i}' for i in range(len(results))]
    t = results[0][1]['t']

    for ax, key, ref_key, ylabel, title in [
        (axes[0], 'P_pos', 'rp', 'Pressure [kPa]', 'ch0 Positive – gain comparison'),
        (axes[1], 'P_neg', 'rn', 'Pressure [kPa]', 'ch6 Negative – gain comparison'),
    ]:
        ax.plot(t, results[0][1][ref_key], 'k--', lw=1.5, label='ref', zorder=5)
        for i, (label, d) in enumerate(results):
            e = rmse(d[key], d[ref_key], t)
            ax.plot(t, d[key], color=colors[i], lw=1.2,
                    label=f'{label}  RMSE={e:.2f}')
        for xv in [2,6,10,14]: ax.axvline(xv, color='gray', lw=0.6, ls=':')
        ax.set_xlabel('Time [s]'); ax.set_ylabel(ylabel); ax.set_title(title)
        ax.legend(fontsize=8); ax.grid(True, alpha=0.3); ax.set_xlim(0, T_TOTAL)

    plt.tight_layout()
    plt.savefig(path, dpi=150, bbox_inches='tight')
    plt.close()

