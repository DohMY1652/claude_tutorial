def make_params(row):
    lbl, TC_p, kmi_p, kma_p, kat_p, mt_p, TC_n, kmi_n, kma_n, kat_n, mt_n = row
    pos = {**BASE_POS, 'TC':TC_p,'ki_mi':kmi_p,'ki_ma':kma_p,'ki_at':kat_p,'macro_thr':mt_p}
    neg = {**BASE_NEG, 'TC':TC_n,'ki_mi':kmi_n,'ki_ma':kma_n,'ki_at':kat_n,'macro_thr':mt_n}
    return lbl, pos, neg

